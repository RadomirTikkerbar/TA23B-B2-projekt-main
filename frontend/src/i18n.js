const storedLocale = typeof localStorage === 'undefined' ? 'en' : localStorage.getItem('locale')
export const locale = ref(languages.some(language => language.code === storedLocale) ? storedLocale : 'en')

export function setLocale (code) {
  if (!languages.some(language => language.code === code)) {
    throw new Error(`Unsupported language: ${code}`)
  }
  locale.value = code
  localStorage.setItem('locale', code)
}

export function useI18n () {
  function t (key, values = {}) {
    let text = messages[locale.value][key] || messages.en[key] || key
    for (const [name, value] of Object.entries(values)) {
      text = text.replaceAll(`{${name}}`, String(value))
    }
    return text
  }

  return { locale, languages, setLocale, t }
}
